-- AXORA SOLUTIONS · V005 · Promociones y beneficio de primeros aliados

CREATE TABLE PROMOCIONES (
  ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE             VARCHAR2(150) NOT NULL,
  CODIGO             VARCHAR2(40) NOT NULL,
  DESCRIPCION        VARCHAR2(1000),
  TIPO_DESCUENTO     VARCHAR2(10) DEFAULT 'PORCENTAJE' NOT NULL CHECK (TIPO_DESCUENTO IN ('PORCENTAJE','VALOR')),
  VALOR_DESCUENTO    NUMBER(14,2) NOT NULL CHECK (VALOR_DESCUENTO > 0),
  MAX_BENEFICIARIOS  NUMBER(6) DEFAULT 10 NOT NULL CHECK (MAX_BENEFICIARIOS > 0),
  USOS_POR_CLIENTE   NUMBER(4) DEFAULT 1 NOT NULL CHECK (USOS_POR_CLIENTE > 0),
  VALOR_MINIMO       NUMBER(14,2) DEFAULT 0 NOT NULL CHECK (VALOR_MINIMO >= 0),
  FECHA_INICIO       DATE NOT NULL,
  FECHA_FIN          DATE NOT NULL,
  ACTIVA             NUMBER(1) DEFAULT 0 NOT NULL CHECK (ACTIVA IN (0,1)),
  CREADO_EN          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN     TIMESTAMP,
  CONSTRAINT UQ_PROMOCION_CODIGO UNIQUE (CODIGO),
  CONSTRAINT CK_PROMOCION_FECHAS CHECK (FECHA_FIN >= FECHA_INICIO),
  CONSTRAINT CK_PROMOCION_PCT CHECK (TIPO_DESCUENTO <> 'PORCENTAJE' OR VALOR_DESCUENTO <= 100)
)
/
-- Si no tiene servicios asociados, la promoción aplica a todos; si los tiene, solo a esos.
CREATE TABLE PROMOCION_SERVICIOS (
  PROMOCION_ID NUMBER NOT NULL REFERENCES PROMOCIONES(ID),
  SERVICIO_ID  NUMBER NOT NULL REFERENCES SERVICIOS(ID),
  CONSTRAINT PK_PROMOCION_SERVICIOS PRIMARY KEY (PROMOCION_ID, SERVICIO_ID)
)
/
CREATE TABLE PROMOCION_BENEFICIARIOS (
  ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROMOCION_ID      NUMBER NOT NULL REFERENCES PROMOCIONES(ID),
  EMAIL             VARCHAR2(150) NOT NULL,
  NOMBRE            VARCHAR2(150),
  CODIGO_INDIVIDUAL VARCHAR2(40),
  USUARIO_ID        NUMBER REFERENCES USUARIOS(ID) ON DELETE SET NULL,
  CREADO_POR        NUMBER REFERENCES USUARIOS(ID) ON DELETE SET NULL,
  CREADO_EN         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_PROMO_BENEF_EMAIL UNIQUE (PROMOCION_ID, EMAIL),
  CONSTRAINT UQ_PROMO_BENEF_CODIGO UNIQUE (CODIGO_INDIVIDUAL)
)
/
CREATE TABLE PROMOCION_USOS (
  ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROMOCION_ID     NUMBER NOT NULL REFERENCES PROMOCIONES(ID),
  BENEFICIARIO_ID  NUMBER NOT NULL REFERENCES PROMOCION_BENEFICIARIOS(ID),
  COTIZACION_ID    NUMBER NOT NULL REFERENCES COTIZACIONES(ID),
  VALOR_DESCUENTO  NUMBER(14,2) NOT NULL CHECK (VALOR_DESCUENTO >= 0),
  ESTADO           VARCHAR2(10) DEFAULT 'RESERVADO' NOT NULL CHECK (ESTADO IN ('RESERVADO','APLICADO','LIBERADO')),
  CREADO_EN        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN   TIMESTAMP
)
/
CREATE INDEX IX_PROMO_USOS_BENEF ON PROMOCION_USOS(PROMOCION_ID, BENEFICIARIO_ID, ESTADO)
/
CREATE INDEX IX_PROMO_USOS_COT ON PROMOCION_USOS(COTIZACION_ID)
/
ALTER TABLE COTIZACIONES ADD (PROMOCION_ID NUMBER REFERENCES PROMOCIONES(ID))
