CREATE TABLE PROPUESTAS_ESPACIO (
  ID                       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMPRESA_ID               NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  CREADO_POR               NUMBER NOT NULL REFERENCES USUARIOS(ID),
  ESTADO                   VARCHAR2(24) DEFAULT 'BORRADOR' NOT NULL
                           CHECK (ESTADO IN ('BORRADOR','ANALIZADA','LISTA','SOLICITUD_CREADA','ELIMINADA')),
  FOTOGRAFIA_ARCHIVO       VARCHAR2(300),
  FOTOGRAFIA_NOMBRE        VARCHAR2(255),
  FOTOGRAFIA_MIME          VARCHAR2(30),
  FOTOGRAFIA_TAMANO        NUMBER(12),
  SERVICIOS_JSON           VARCHAR2(4000),
  OBSERVACIONES_CLIENTE    VARCHAR2(1000),
  ANALISIS_JSON            VARCHAR2(4000),
  CONSENTIMIENTO_GEMINI_EN TIMESTAMP,
  SOLICITUD_ID             NUMBER UNIQUE REFERENCES SOLICITUDES(ID),
  CREADO_EN                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN           TIMESTAMP
)
/
CREATE INDEX IX_PROP_ESP_EMPRESA ON PROPUESTAS_ESPACIO(EMPRESA_ID, CREADO_EN)
/
CREATE INDEX IX_PROP_ESP_CREADOR ON PROPUESTAS_ESPACIO(CREADO_POR, CREADO_EN)
/

CREATE TABLE PROPUESTA_ESPACIO_VERSIONES (
  ID                       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROPUESTA_ID             NUMBER NOT NULL REFERENCES PROPUESTAS_ESPACIO(ID) ON DELETE CASCADE,
  NUMERO                   NUMBER(5) NOT NULL CHECK (NUMERO > 0),
  IMAGEN_ARCHIVO           VARCHAR2(300) NOT NULL,
  IMAGEN_MIME              VARCHAR2(30) NOT NULL CHECK (IMAGEN_MIME IN ('image/jpeg','image/png','image/webp')),
  IMAGEN_TAMANO            NUMBER(12) NOT NULL CHECK (IMAGEN_TAMANO > 0),
  DESCRIPCION              VARCHAR2(2000) NOT NULL,
  MATERIALES_JSON          VARCHAR2(3000) NOT NULL,
  OBSERVACIONES_JSON       VARCHAR2(3000) NOT NULL,
  RECOMENDACIONES_JSON     VARCHAR2(4000) NOT NULL,
  MODELO                   VARCHAR2(100) NOT NULL,
  CREADO_EN                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_PROP_ESP_VERSION UNIQUE (PROPUESTA_ID, NUMERO)
)
/

CREATE TABLE PROPUESTA_ESPACIO_SERVICIOS (
  ID                       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  VERSION_ID               NUMBER NOT NULL REFERENCES PROPUESTA_ESPACIO_VERSIONES(ID) ON DELETE CASCADE,
  SERVICIO_ID              NUMBER REFERENCES SERVICIOS(ID),
  CLAVE                    VARCHAR2(50) NOT NULL,
  CODIGO                   VARCHAR2(30),
  NOMBRE                   VARCHAR2(150) NOT NULL,
  ESPECIFICACIONES         VARCHAR2(1000),
  CONSTRAINT UQ_PROP_ESP_SERV UNIQUE (VERSION_ID, CLAVE)
)
/
