-- ============ SEGURIDAD ============
CREATE TABLE ROLES (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO      VARCHAR2(30)  NOT NULL UNIQUE,
  NOMBRE      VARCHAR2(80)  NOT NULL,
  DESCRIPCION VARCHAR2(255)
)
/
CREATE TABLE PERMISOS (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO      VARCHAR2(60)  NOT NULL UNIQUE,
  DESCRIPCION VARCHAR2(255)
)
/
CREATE TABLE ROL_PERMISO (
  ROL_ID     NUMBER NOT NULL REFERENCES ROLES(ID),
  PERMISO_ID NUMBER NOT NULL REFERENCES PERMISOS(ID),
  CONSTRAINT PK_ROL_PERMISO PRIMARY KEY (ROL_ID, PERMISO_ID)
)
/

-- ============ EMPRESAS ============
CREATE TABLE EMPRESAS (
  ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NIT              VARCHAR2(20)  NOT NULL UNIQUE,
  RAZON_SOCIAL     VARCHAR2(200) NOT NULL,
  NOMBRE_COMERCIAL VARCHAR2(200),
  SECTOR           VARCHAR2(100),
  DIRECCION        VARCHAR2(250),
  CIUDAD           VARCHAR2(100) DEFAULT 'Cúcuta' NOT NULL,
  TELEFONO         VARCHAR2(40),
  EMAIL            VARCHAR2(150),
  ACTIVO           NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_EN        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN   TIMESTAMP
)
/
CREATE TABLE SEDES (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMPRESA_ID     NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  NOMBRE         VARCHAR2(150) NOT NULL,
  DIRECCION      VARCHAR2(250),
  CIUDAD         VARCHAR2(100),
  TELEFONO       VARCHAR2(40),
  ACTIVO         NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_EN      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN TIMESTAMP
)
/
CREATE TABLE CONTACTOS (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMPRESA_ID     NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  SEDE_ID        NUMBER REFERENCES SEDES(ID),
  NOMBRE         VARCHAR2(150) NOT NULL,
  CARGO          VARCHAR2(100),
  EMAIL          VARCHAR2(150),
  TELEFONO       VARCHAR2(40),
  WHATSAPP       VARCHAR2(40),
  PRINCIPAL      NUMBER(1) DEFAULT 0 NOT NULL CHECK (PRINCIPAL IN (0,1)),
  ACTIVO         NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_EN      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN TIMESTAMP
)
/
CREATE TABLE USUARIOS (
  ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMPRESA_ID        NUMBER REFERENCES EMPRESAS(ID),          -- NULL para personal de MS
  EMAIL             VARCHAR2(150) NOT NULL UNIQUE,           -- se guarda en minúsculas
  NOMBRE            VARCHAR2(150) NOT NULL,
  TELEFONO          VARCHAR2(40),
  PASSWORD_HASH     VARCHAR2(100) NOT NULL,                  -- bcrypt
  ACTIVO            NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  INTENTOS_FALLIDOS NUMBER(3) DEFAULT 0 NOT NULL,
  BLOQUEADO_HASTA   TIMESTAMP,
  ULTIMO_ACCESO     TIMESTAMP,
  CREADO_EN         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN    TIMESTAMP
)
/
CREATE TABLE USUARIO_ROL (
  USUARIO_ID NUMBER NOT NULL REFERENCES USUARIOS(ID),
  ROL_ID     NUMBER NOT NULL REFERENCES ROLES(ID),
  CONSTRAINT PK_USUARIO_ROL PRIMARY KEY (USUARIO_ID, ROL_ID)
)
/
CREATE TABLE REFRESH_TOKENS (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID  NUMBER NOT NULL REFERENCES USUARIOS(ID),
  TOKEN_HASH  VARCHAR2(64) NOT NULL UNIQUE,                  -- SHA-256 del token (nunca el token)
  FAMILIA     VARCHAR2(36) NOT NULL,
  EXPIRA_EN   TIMESTAMP NOT NULL,
  REVOCADO    NUMBER(1) DEFAULT 0 NOT NULL CHECK (REVOCADO IN (0,1)),
  IP          VARCHAR2(60),
  USER_AGENT  VARCHAR2(300),
  CREADO_EN   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE PASSWORD_RESETS (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID  NUMBER NOT NULL REFERENCES USUARIOS(ID),
  TOKEN_HASH  VARCHAR2(64) NOT NULL UNIQUE,
  EXPIRA_EN   TIMESTAMP NOT NULL,
  USADO       NUMBER(1) DEFAULT 0 NOT NULL CHECK (USADO IN (0,1)),
  CREADO_EN   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE AUDITORIA (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID NUMBER,
  ACCION     VARCHAR2(60)  NOT NULL,
  ENTIDAD    VARCHAR2(40),
  ENTIDAD_ID NUMBER,
  DETALLE    VARCHAR2(4000),
  IP         VARCHAR2(60),
  FECHA      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/

-- ============ CATÁLOGO Y ACTIVOS ============
CREATE TABLE SERVICIOS (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  LINEA          VARCHAR2(20) NOT NULL CHECK (LINEA IN ('SOPORTE_EQUIPOS','REDES','CCTV')),
  CODIGO         VARCHAR2(30) NOT NULL UNIQUE,
  NOMBRE         VARCHAR2(150) NOT NULL,
  DESCRIPCION    VARCHAR2(1000),
  PRECIO_BASE    NUMBER(14,2) DEFAULT 0 NOT NULL CHECK (PRECIO_BASE >= 0),
  UNIDAD         VARCHAR2(30) DEFAULT 'servicio' NOT NULL,
  ACTIVO         NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_EN      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN TIMESTAMP
)
/
CREATE TABLE EQUIPOS (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMPRESA_ID     NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  SEDE_ID        NUMBER REFERENCES SEDES(ID),
  TIPO           VARCHAR2(20) NOT NULL CHECK (TIPO IN ('COMPUTADOR','PORTATIL','CAMARA','DVR_NVR','ROUTER','SWITCH','ACCESS_POINT','IMPRESORA','OTRO')),
  NOMBRE         VARCHAR2(150) NOT NULL,
  MARCA          VARCHAR2(80),
  MODELO         VARCHAR2(80),
  SERIAL         VARCHAR2(100),
  UBICACION      VARCHAR2(200),
  FECHA_COMPRA   DATE,
  GARANTIA_HASTA DATE,
  DESCRIPCION    VARCHAR2(1000),
  ESTADO         VARCHAR2(20) DEFAULT 'OPERATIVO' NOT NULL CHECK (ESTADO IN ('OPERATIVO','EN_REPARACION','FUERA_DE_SERVICIO','BAJA')),
  ACTIVO         NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_EN      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN TIMESTAMP
)
/

-- ============ SOLICITUDES ============
CREATE TABLE SOLICITUDES (
  ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO           VARCHAR2(20) GENERATED ALWAYS AS ('SOL-' || TO_CHAR(ID, 'FM000000')) VIRTUAL,
  EMPRESA_ID       NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  SEDE_ID          NUMBER REFERENCES SEDES(ID),
  EQUIPO_ID        NUMBER REFERENCES EQUIPOS(ID),
  SERVICIO_ID      NUMBER REFERENCES SERVICIOS(ID),
  SOLICITANTE_ID   NUMBER NOT NULL REFERENCES USUARIOS(ID),
  TECNICO_ID       NUMBER REFERENCES USUARIOS(ID),
  CATEGORIA        VARCHAR2(20) NOT NULL CHECK (CATEGORIA IN ('SOPORTE_EQUIPOS','REDES','CCTV','OTRO')),
  ASUNTO           VARCHAR2(200) NOT NULL,
  DESCRIPCION      VARCHAR2(4000) NOT NULL,
  PRIORIDAD        VARCHAR2(10) DEFAULT 'MEDIA' NOT NULL CHECK (PRIORIDAD IN ('BAJA','MEDIA','ALTA','URGENTE')),
  ESTADO           VARCHAR2(20) DEFAULT 'NUEVA' NOT NULL CHECK (ESTADO IN ('NUEVA','EN_REVISION','COTIZADA','AUTORIZADA','EN_PROCESO','RESUELTA','CERRADA','CANCELADA')),
  FECHA_PROGRAMADA DATE,
  FECHA_CIERRE     DATE,
  OBSERVACIONES    VARCHAR2(4000),
  CREADO_EN        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN   TIMESTAMP
)
/
CREATE TABLE ADJUNTOS (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ENTIDAD         VARCHAR2(20) NOT NULL CHECK (ENTIDAD IN ('SOLICITUD','ORDEN')),
  ENTIDAD_ID      NUMBER NOT NULL,
  EMPRESA_ID      NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  TIPO            VARCHAR2(12) DEFAULT 'ADJUNTO' NOT NULL CHECK (TIPO IN ('ADJUNTO','EVIDENCIA')),
  NOMBRE_ORIGINAL VARCHAR2(255) NOT NULL,
  NOMBRE_ARCHIVO  VARCHAR2(120) NOT NULL,                    -- nombre aleatorio en disco
  MIME            VARCHAR2(100) NOT NULL,
  TAMANO          NUMBER(12) NOT NULL,
  SUBIDO_POR      NUMBER NOT NULL REFERENCES USUARIOS(ID),
  ACTIVO          NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_EN       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE ASIGNACIONES (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ENTIDAD      VARCHAR2(20) NOT NULL CHECK (ENTIDAD IN ('SOLICITUD','ORDEN','MANTENIMIENTO')),
  ENTIDAD_ID   NUMBER NOT NULL,
  TECNICO_ID   NUMBER NOT NULL REFERENCES USUARIOS(ID),
  ASIGNADO_POR NUMBER NOT NULL REFERENCES USUARIOS(ID),
  ACTIVA       NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVA IN (0,1)),
  FECHA        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/

-- ============ COTIZACIONES ============
CREATE TABLE COTIZACIONES (
  ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO           VARCHAR2(20) GENERATED ALWAYS AS ('COT-' || TO_CHAR(ID, 'FM000000')) VIRTUAL,
  EMPRESA_ID       NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  SOLICITUD_ID     NUMBER REFERENCES SOLICITUDES(ID),
  CREADO_POR       NUMBER NOT NULL REFERENCES USUARIOS(ID),
  ESTADO           VARCHAR2(12) DEFAULT 'BORRADOR' NOT NULL CHECK (ESTADO IN ('BORRADOR','ENVIADA','APROBADA','RECHAZADA','VENCIDA','ANULADA')),
  FECHA_EMISION    DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
  VALIDEZ_HASTA    DATE,
  SUBTOTAL         NUMBER(14,2) DEFAULT 0 NOT NULL,
  DESCUENTO        NUMBER(14,2) DEFAULT 0 NOT NULL,
  IVA_PORCENTAJE   NUMBER(5,2)  DEFAULT 19 NOT NULL,
  IVA_VALOR        NUMBER(14,2) DEFAULT 0 NOT NULL,
  TOTAL            NUMBER(14,2) DEFAULT 0 NOT NULL,
  NOTAS            VARCHAR2(2000),
  MOTIVO_RECHAZO   VARCHAR2(1000),
  RESPONDIDO_POR   NUMBER REFERENCES USUARIOS(ID),
  FECHA_RESPUESTA  TIMESTAMP,
  CREADO_EN        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN   TIMESTAMP
)
/
CREATE TABLE DETALLE_COTIZACION (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COTIZACION_ID   NUMBER NOT NULL REFERENCES COTIZACIONES(ID) ON DELETE CASCADE,
  SERVICIO_ID     NUMBER REFERENCES SERVICIOS(ID),
  DESCRIPCION     VARCHAR2(300) NOT NULL,
  CANTIDAD        NUMBER(10,2) NOT NULL CHECK (CANTIDAD > 0),
  PRECIO_UNITARIO NUMBER(14,2) NOT NULL CHECK (PRECIO_UNITARIO >= 0),
  TOTAL_LINEA     NUMBER(14,2) NOT NULL
)
/

-- ============ ÓRDENES DE SERVICIO ============
CREATE TABLE ORDENES_SERVICIO (
  ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO             VARCHAR2(20) GENERATED ALWAYS AS ('OS-' || TO_CHAR(ID, 'FM000000')) VIRTUAL,
  EMPRESA_ID         NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  SEDE_ID            NUMBER REFERENCES SEDES(ID),
  SOLICITUD_ID       NUMBER REFERENCES SOLICITUDES(ID),
  COTIZACION_ID      NUMBER REFERENCES COTIZACIONES(ID),
  EQUIPO_ID          NUMBER REFERENCES EQUIPOS(ID),
  SERVICIO_ID        NUMBER REFERENCES SERVICIOS(ID),
  TECNICO_ID         NUMBER REFERENCES USUARIOS(ID),
  CREADO_POR         NUMBER NOT NULL REFERENCES USUARIOS(ID),
  ESTADO             VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL CHECK (ESTADO IN ('PENDIENTE','ASIGNADA','EN_EJECUCION','FINALIZADA','CERRADA','CANCELADA')),
  PRIORIDAD          VARCHAR2(10) DEFAULT 'MEDIA' NOT NULL CHECK (PRIORIDAD IN ('BAJA','MEDIA','ALTA','URGENTE')),
  DESCRIPCION_TRABAJO VARCHAR2(4000),
  DIAGNOSTICO        VARCHAR2(4000),
  SOLUCION           VARCHAR2(4000),
  FECHA_PROGRAMADA   DATE,
  FECHA_INICIO       TIMESTAMP,
  FECHA_FIN          TIMESTAMP,
  FECHA_CIERRE       TIMESTAMP,
  CREADO_EN          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN     TIMESTAMP
)
/
CREATE TABLE DETALLE_ORDEN (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ORDEN_ID       NUMBER NOT NULL REFERENCES ORDENES_SERVICIO(ID),
  TIPO           VARCHAR2(10) NOT NULL CHECK (TIPO IN ('ACTIVIDAD','MATERIAL')),
  DESCRIPCION    VARCHAR2(500) NOT NULL,
  CANTIDAD       NUMBER(10,2) DEFAULT 1 NOT NULL CHECK (CANTIDAD > 0),
  COSTO_UNITARIO NUMBER(14,2) DEFAULT 0 NOT NULL CHECK (COSTO_UNITARIO >= 0),
  REGISTRADO_POR NUMBER NOT NULL REFERENCES USUARIOS(ID),
  FECHA          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/

-- ============ PLANES Y CONTRATOS ============
CREATE TABLE PLANES (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO         VARCHAR2(30) NOT NULL UNIQUE,
  NOMBRE         VARCHAR2(150) NOT NULL,
  DESCRIPCION    VARCHAR2(1000),
  ALCANCE        VARCHAR2(2000),
  PRECIO_MENSUAL NUMBER(14,2) NOT NULL CHECK (PRECIO_MENSUAL >= 0),
  VISITAS_MES    NUMBER(3) DEFAULT 1 NOT NULL,
  ACTIVO         NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_EN      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN TIMESTAMP
)
/
CREATE TABLE PLAN_SERVICIO (
  PLAN_ID     NUMBER NOT NULL REFERENCES PLANES(ID),
  SERVICIO_ID NUMBER NOT NULL REFERENCES SERVICIOS(ID),
  CONSTRAINT PK_PLAN_SERVICIO PRIMARY KEY (PLAN_ID, SERVICIO_ID)
)
/
CREATE TABLE CONTRATOS (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO         VARCHAR2(20) GENERATED ALWAYS AS ('CTR-' || TO_CHAR(ID, 'FM000000')) VIRTUAL,
  EMPRESA_ID     NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  PLAN_ID        NUMBER NOT NULL REFERENCES PLANES(ID),
  FECHA_INICIO   DATE NOT NULL,
  FECHA_FIN      DATE NOT NULL,
  PRECIO_MENSUAL NUMBER(14,2) NOT NULL CHECK (PRECIO_MENSUAL >= 0),
  ESTADO         VARCHAR2(12) DEFAULT 'VIGENTE' NOT NULL CHECK (ESTADO IN ('VIGENTE','SUSPENDIDO','VENCIDO','CANCELADO')),
  OBSERVACIONES  VARCHAR2(2000),
  CREADO_EN      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN TIMESTAMP,
  CONSTRAINT CK_CONTRATO_FECHAS CHECK (FECHA_FIN > FECHA_INICIO)
)
/
CREATE TABLE PAGOS (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMPRESA_ID     NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  ORDEN_ID       NUMBER REFERENCES ORDENES_SERVICIO(ID),
  CONTRATO_ID    NUMBER REFERENCES CONTRATOS(ID),
  MONTO          NUMBER(14,2) NOT NULL CHECK (MONTO > 0),
  METODO         VARCHAR2(30) NOT NULL,
  REFERENCIA     VARCHAR2(100),
  FECHA_PAGO     DATE NOT NULL,
  REGISTRADO_POR NUMBER NOT NULL REFERENCES USUARIOS(ID),
  CREADO_EN      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/

-- ============ MANTENIMIENTOS ============
CREATE TABLE MANTENIMIENTOS (
  ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO              VARCHAR2(20) GENERATED ALWAYS AS ('MTO-' || TO_CHAR(ID, 'FM000000')) VIRTUAL,
  EMPRESA_ID          NUMBER NOT NULL REFERENCES EMPRESAS(ID),
  SEDE_ID             NUMBER REFERENCES SEDES(ID),
  EQUIPO_ID           NUMBER REFERENCES EQUIPOS(ID),
  CONTRATO_ID         NUMBER REFERENCES CONTRATOS(ID),
  TECNICO_ID          NUMBER REFERENCES USUARIOS(ID),
  CREADO_POR          NUMBER NOT NULL REFERENCES USUARIOS(ID),
  TIPO                VARCHAR2(12) NOT NULL CHECK (TIPO IN ('PREVENTIVO','CORRECTIVO')),
  TITULO              VARCHAR2(200) NOT NULL,
  DESCRIPCION         VARCHAR2(2000),
  ESTADO              VARCHAR2(15) DEFAULT 'PROGRAMADO' NOT NULL CHECK (ESTADO IN ('PROGRAMADO','EN_EJECUCION','COMPLETADO','CANCELADO')),
  FECHA_PROGRAMADA    DATE NOT NULL,
  FRECUENCIA_DIAS     NUMBER(5),
  FECHA_INICIO        TIMESTAMP,
  FECHA_EJECUCION     TIMESTAMP,
  RESULTADO           VARCHAR2(4000),
  PROXIMO_VENCIMIENTO DATE,
  CREADO_EN           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ACTUALIZADO_EN      TIMESTAMP
)
/

-- ============ HISTORIAL Y NOTIFICACIONES ============
-- Historial único: cubre empresa, equipo, solicitud, cotización, orden y mantenimiento.
CREATE TABLE HISTORIAL_ESTADOS (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ENTIDAD         VARCHAR2(20) NOT NULL CHECK (ENTIDAD IN ('SOLICITUD','COTIZACION','ORDEN','MANTENIMIENTO','EQUIPO','EMPRESA')),
  ENTIDAD_ID      NUMBER NOT NULL,
  EMPRESA_ID      NUMBER REFERENCES EMPRESAS(ID),
  EQUIPO_ID       NUMBER REFERENCES EQUIPOS(ID),
  ESTADO_ANTERIOR VARCHAR2(20),
  ESTADO_NUEVO    VARCHAR2(20) NOT NULL,
  COMENTARIO      VARCHAR2(1000),
  USUARIO_ID      NUMBER REFERENCES USUARIOS(ID),
  FECHA           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE PLANTILLAS_NOTIFICACION (
  ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO VARCHAR2(60) NOT NULL,
  CANAL  VARCHAR2(10) NOT NULL CHECK (CANAL IN ('INTERNA','EMAIL','WHATSAPP')),
  ASUNTO VARCHAR2(200),
  CUERPO VARCHAR2(2000) NOT NULL,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CONSTRAINT UQ_PLANTILLA UNIQUE (CODIGO, CANAL)
)
/
CREATE TABLE NOTIFICACIONES (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID   NUMBER NOT NULL REFERENCES USUARIOS(ID),
  EMPRESA_ID   NUMBER REFERENCES EMPRESAS(ID),
  TIPO         VARCHAR2(40) NOT NULL,
  TITULO       VARCHAR2(200) NOT NULL,
  MENSAJE      VARCHAR2(1000),
  ENLACE       VARCHAR2(200),
  CANAL        VARCHAR2(10) DEFAULT 'INTERNA' NOT NULL CHECK (CANAL IN ('INTERNA','EMAIL','WHATSAPP')),
  ESTADO_ENVIO VARCHAR2(12) DEFAULT 'NO_APLICA' NOT NULL CHECK (ESTADO_ENVIO IN ('NO_APLICA','PENDIENTE','ENVIADA','ERROR')),
  LEIDA        NUMBER(1) DEFAULT 0 NOT NULL CHECK (LEIDA IN (0,1)),
  CREADO_EN    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/

